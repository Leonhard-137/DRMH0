#!/usr/bin/env python3
# 从 relaxed-Gamma 和 shared-SED 的已完成结果生成论文表、宏与来源清单。
# 本模块使用 RMS SED（lambda*R），与 sed_u_diagnostics 的差分光谱入口须分清。
# 各波段距离只是诊断；论文联合 H0 读取每个源一个 shared-SED 光度距离。
"""Render paper tables from the completed relaxed-Gamma result family.

No MICA, FFA or lag inference is run. The U diagnostic is an analytic
leave-U-out power-law fit to each existing joint FFA RMS posterior draw.
All generated files are kept below DRMH0/tables/relaxed by default.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import numpy as np
import pandas as pd
import yaml


ROOT = Path(__file__).resolve().parents[1]
STAGE = "mica_gamma2_physw_relaxed"
BANDS = ("UVW2", "UVM2", "UVW1", "U", "B", "V")
ALIASES = {"W2": "UVW2", "M2": "UVM2", "W1": "UVW1"}


def band_name(value):
    return ALIASES.get(str(value), str(value))


def tex_name(source):
    base, separator, segment = source.partition("_")
    base = re.sub(r"^(Mrk|NGC)(?=\d)", r"\1~", base)
    base = re.sub(r"^F(?=\d)", "Fairall~", base)
    return base


# 参数 low/high 已是相对中心值的非负误差量，不是区间端点。
def interval(median, low, high, digits=3):
    values = np.asarray([median, low, high], float)
    if not np.isfinite(values).all() or np.any(values[1:] < 0):
        raise ValueError(f"Invalid interval: {values}")
    return f"${median:.{digits}f}_{{-{low:.{digits}f}}}^{{+{high:.{digits}f}}}$"


def compact_table(columns, caption, label, head, rows, explanation):
    """Use a normal column float for the short U-excess table."""
    return "\n".join([
        "% Generated by src/render_paper_result_tables.py; edit the generator.",
        r"\begin{table}[!htbp]", r"\centering",
        r"\caption{" + caption + "}", r"\label{" + label + "}",
        r"{\footnotesize", r"\begin{tabular}{" + columns + "}",
        r"\hline\hline", head + r" \\", r"\hline", *rows,
        r"\hline", r"\end{tabular}\par}", r"\smallskip",
        r"\parbox{\columnwidth}{\footnotesize " + explanation + "}",
        r"\end{table}", "",
    ])


def table(columns, caption, labels, head, rows, explanation, size="footnotesize", long_table=False, placement=None):
    return "\n".join([
        "% Generated by src/render_paper_result_tables.py; edit the generator.",
        *([r"\startlongtable"] if long_table else []),
        r"\begin{deluxetable*}{@{\extracolsep{\fill}}" + columns + "@{}}"
        + ("[" + placement + "]" if placement else ""),
        "\\tabletypesize{\\" + size + "}",
        "% AASTeX measures and prints with tabular; expand both passes locally.",
        r"\def\tabular{\csname tabular*\endcsname{\textwidth}}",
        r"\tablewidth{\textwidth}",
        r"\tablecaption{" + caption + "\n" + "\n".join(
            r"\label{" + label + "}" for label in labels) + "}",
        r"\tablehead{" + head + "}", r"\startdata", *rows,
        r"\enddata", r"\tablecomments{" + explanation + "}",
        r"\end{deluxetable*}", r"\global\startlongtablefalse", "",
    ])


# 按指定键筛出唯一行；重复或缺失结果属于身份/版本不一致，不能取第一行凑数。
def only(frame, **criteria):
    selected = frame
    for column, value in criteria.items():
        selected = selected[selected[column].eq(value)]
    if len(selected) != 1:
        raise ValueError(f"Expected one row for {criteria}; got {len(selected)}")
    return selected.iloc[0]


# 在每个联合 FFA 样本中，用非U波段的 lambda*R 做对数幂律回归并预测U。
# 权重来自边际 RMS 相对误差近似；保留样本内关联，但回归权重矩阵是对角的。
def u_rms_diagnostic(source, stage_name, points_path, posterior_path):
    points = pd.read_csv(points_path).sort_values("wavelength_angstrom")
    posterior = pd.read_csv(posterior_path, sep=r"\s+")
    columns = []
    for band in points["band"]:
        candidates = [f"R_{band}", f"R_{band_name(band)}"]
        column = next((name for name in candidates if name in posterior), None)
        if column is None:
            raise KeyError(f"No RMS column for {band} in {posterior_path}")
        columns.append(column)
    waves = points["wavelength_angstrom"].to_numpy(float)
    values = posterior[columns].to_numpy(float) * waves[None, :]
    valid = np.all(np.isfinite(values) & (values > 0), axis=1)
    values = values[valid]
    if len(values) < 20:
        raise ValueError(f"Too few joint RMS posterior draws: {posterior_path}")
    bands = [band_name(band) for band in points["band"]]
    if set(bands) != set(BANDS) or len(bands) != 6:
        raise ValueError(f"Expected all six UVOT bands: {points_path}")
    u_index = bands.index("U")
    use = np.arange(len(bands)) != u_index
    q16, q50, q84 = np.percentile(values, [16, 50, 84], axis=0)
    sigma_log = np.maximum(0.5 * (q84 - q16) / q50, 1.0e-4)
    x = np.log(waves / np.exp(np.mean(np.log(waves))))
    y = np.log(values[:, use])
    weight = 1 / sigma_log[use] ** 2
    xbar = np.average(x[use], weights=weight)
    ybar = np.average(y, weights=weight, axis=1)
    alpha = np.sum(weight * (x[use] - xbar) * (y - ybar[:, None]), axis=1)
    alpha /= np.sum(weight * (x[use] - xbar) ** 2)
    intercept = ybar - alpha * xbar
    predicted = np.exp(intercept + alpha * x[u_index])
    ratio = values[:, u_index] / predicted
    # 百分比过量定义：100*(实际U/非U拟合预测U-1)，并非BLR贡献比例的直接测量。
    percentages = 100 * (ratio - 1)
    row = dict(source=source, stage=stage_name, quantity="lambda_R_lambda",
               fit_model="free", excluded_band="U", fit_bands=";".join(
                   band for band in bands if band != "U"),
               n_input=len(posterior), n_posterior=len(values),
               valid_fraction=float(valid.mean()),
               input_points=str(points_path), input_posterior=str(posterior_path),
               weighting="inverse variance of marginal RMS log-error approximation")
    for name, vector in (("alpha", alpha), ("u_excess_percent", percentages),
                         ("observed_over_predicted", ratio)):
        for q, value in zip((16, 50, 84), np.percentile(vector, [16, 50, 84])):
            row[f"{name}_p{q}"] = float(value)
    return row


# 核对配置路径、stage、样本身份和量定义后生成表格。
# 普通保存距离在这里乘(1+z)得到D_L；shared-SED已存D_L，不再乘一次。
def render(workspace, downstream, output):
    sample_path = workspace / "DRMH0/tables/sample_observations.csv"
    summary_path = downstream / "summary.csv"
    sample = pd.read_csv(sample_path)
    summary = pd.read_csv(summary_path)
    if set(summary["stage"]) != {STAGE}:
        raise ValueError("Downstream summary is not exclusively the relaxed branch")
    sources = [source for source in sample["source"] if source in set(summary["source"])]
    omitted = [source for source in sample["source"] if source not in sources]
    if len(sources) != len(summary) or len(sources) != len(set(sources)):
        raise ValueError("Sample and downstream summary identities do not agree")
    sed_path, lag_path = downstream / "all_sed.csv", downstream / "all_lag.csv"
    distance_path = downstream / "all_distance.csv"
    sed, lag, distances = map(pd.read_csv, (sed_path, lag_path, distance_path))
    provenance = {source: {} for source in sources}
    fit_rows, u_rows, mica_rows, distance_rows = [], [], [], []

    for source in sources:
        cfg_path = workspace / source / "config/source_config.yaml"
        cfg = yaml.safe_load(cfg_path.read_text())
        configured = (workspace / source / cfg[STAGE]["output_root"] / "2comp/result/comp0").resolve()
        result = Path(only(summary, source=source)["result_dir"]).resolve()
        if result != configured:
            raise ValueError(f"Relaxed result/config mismatch for {source}")
        provenance[source]["configuration"] = str(cfg_path)
        s_fixed = only(sed, source_dir=source, model="standard")
        s_free = only(sed, source_dir=source, model="free")
        l_fixed = only(lag, source_dir=source, fit_model="4/3")
        l_free = only(lag, source_dir=source, fit_model="free")
        if s_fixed["sed_quantity"] != "lambda_R_lambda" or s_free["sed_quantity"] != "lambda_R_lambda":
            raise ValueError(f"SED summary is not RMS for {source}")
        for name, row in (("sed", s_free), ("lag", l_free)):
            if not Path(row["input_file"]).resolve().is_relative_to(result):
                raise ValueError(f"Wrong {name} input branch for {source}")
            provenance[source][name] = row["input_file"]
        fit_rows.append(dict(
            source=source, stage=STAGE, sed_quantity="lambda_R_lambda",
            alpha=s_free.sed_alpha, alpha_err_low=s_free.sed_alpha_err_minus,
            alpha_err_high=s_free.sed_alpha_err_plus,
            sed_chi2_fixed=s_fixed.chi2, sed_dof_fixed=int(s_fixed.dof),
            sed_chi2_free=s_free.chi2, sed_dof_free=int(s_free.dof),
            beta=l_free.beta, beta_err_low=l_free.beta_err_low, beta_err_high=l_free.beta_err_high,
            lag_chi2_fixed=l_fixed.chi2, lag_dof_fixed=int(l_fixed.dof),
            lag_chi2_free=l_free.chi2, lag_dof_free=int(l_free.dof),
            sed_input=s_free.input_file, lag_input=l_free.input_file))

        total_dir = workspace / source / cfg.get("fflux", {}).get("out", "fflux") / "analysis"
        for name, component, analysis in (("before", "total", total_dir),
                                           ("after", "comp0", result / "fflux/analysis")):
            points_path = analysis / f"{source}_{component}_sed_points.csv"
            post_path = analysis / f"{source}_{component}_6band_flux_posterior.txt"
            u_rows.append(u_rms_diagnostic(source, name, points_path, post_path))
            provenance[source][f"u_{name}"] = [str(points_path), str(post_path)]

        component_path = result.parent / "mica_component_summary.csv"
        rms_path = result / "diagnostics/mica_response_rms.csv"
        components, rms = map(pd.read_csv, (component_path, rms_path))
        components["display_band"] = components["band"].map(band_name)
        rms["display_band"] = rms["band"].map(band_name)
        if set(rms["mica_stage"]) != {STAGE}:
            raise ValueError(f"Wrong RMS branch for {source}")
        for band in BANDS[1:]:
            short = only(components, display_band=band, component="tf0")
            delayed = only(components, display_band=band, component="tf1")
            short_rms = only(rms, display_band=band, component="tf0")
            delayed_rms = only(rms, display_band=band, component="tf1")
            if short.selection != "all" or delayed.selection != "all":
                raise ValueError(f"Selected MICA posterior subset for {source}/{band}")
            if delayed_rms.rms <= 0:
                raise ValueError(f"Nonpositive delayed RMS for {source}/{band}")
            mica_rows.append(dict(source=source, stage=STAGE, band=band,
                tau_short=short.tau, tau_short_err_low=short.tau_err_low,
                tau_short_err_high=short.tau_err_high, tau_delayed=delayed.tau,
                tau_delayed_err_low=delayed.tau_err_low, tau_delayed_err_high=delayed.tau_err_high,
                rms_short=short_rms.rms, rms_delayed=delayed_rms.rms,
                rms_ratio=short_rms.rms / delayed_rms.rms,
                component_input=str(component_path), rms_input=str(rms_path)))
        provenance[source]["mica"] = [str(component_path), str(rms_path)]

        source_dist = distances[distances.source.eq(source) & distances.distance_model.eq("standard")].copy()
        source_dist["display_band"] = source_dist.band.map(band_name)
        for band in BANDS:
            row = only(source_dist, display_band=band)
            if not Path(row.input_file).resolve().is_relative_to(result):
                raise ValueError(f"Wrong distance input branch for {source}")
            factor = 1 + float(row.z)
            distance_rows.append(dict(source=source, stage=STAGE, band=band,
                z=row.z, D_source=row.D_mpc, D_source_err_low=row.D_err_low,
                D_source_err_high=row.D_err_high, D_L_mpc=row.D_mpc * factor,
                D_L_err_low=row.D_err_low * factor, D_L_err_high=row.D_err_high * factor,
                used_in_joint_h0=False, input_file=row.input_file))
        provenance[source]["distance"] = list(source_dist.input_file.unique())

    fits, u, mica, distance = map(pd.DataFrame, (fit_rows, u_rows, mica_rows, distance_rows))
    output.mkdir(parents=True, exist_ok=True)
    for name, frame in (("short_component_fits", fits), ("sed_u_excess", u),
                        ("mica_parameters", mica), ("band_distances", distance)):
        frame.to_csv(output / f"{name}.csv", index=False)

    fit_tex = []
    for r in fits.itertuples():
        fit_tex.append(" & ".join([tex_name(r.source), interval(r.alpha, r.alpha_err_low, r.alpha_err_high),
            f"${r.sed_chi2_fixed:.3f}/{r.sed_dof_fixed}$", f"${r.sed_chi2_free:.3f}/{r.sed_dof_free}$",
            interval(r.beta, r.beta_err_low, r.beta_err_high),
            f"${r.lag_chi2_fixed:.3f}/{r.lag_dof_fixed}$", f"${r.lag_chi2_free:.3f}/{r.lag_dof_free}$"]) + r" \\")
    fit_head = r"""\colhead{AGN} & \multicolumn{3}{c}{SED} & \multicolumn{3}{c}{Lag spectrum} \\
\colhead{} & \colhead{$\alpha_{\rm free}$} & \colhead{$\chi^2/{\rm dof}$} & \colhead{$\chi^2/{\rm dof}$} & \colhead{$\beta_{\rm free}$} & \colhead{$\chi^2/{\rm dof}$} & \colhead{$\chi^2/{\rm dof}$} \\
\colhead{} & \colhead{} & \colhead{Fixed $\alpha$} & \colhead{Free $\alpha$} & \colhead{} & \colhead{Fixed $\beta$} & \colhead{Free $\beta$}"""
    (output / "short_component_fits.tex").write_text(table("lcccccc",
        "Short-component RMS SED and lag-spectrum fits.",
        ["tab:short_component_fits", "tab:short_component_sed", "tab:short_component_lag"],
        fit_head, fit_tex,
        r"The SED index is defined by $\lambda R_\lambda\propto\lambda^\alpha$. "
        r"The fixed indices are $\alpha=-4/3$ and $\beta=4/3$. "
        r"Each $\chi^2/{\rm dof}$ entry lists the statistic followed by the number of degrees of freedom. "
        r"SED statistics are medians over the fitted posterior samples; lag statistics are evaluated at the marginal parameter medians. Neither is a minimum-$\chi^2$ model comparison. "
        r"Uncertainties give the central 68\% posterior intervals."))

    u_tex = []
    for source in sources:
        vals = [tex_name(source)]
        for stage in ("before", "after"):
            r = only(u, source=source, stage=stage)
            vals.append(interval(r.u_excess_percent_p50, r.u_excess_percent_p50-r.u_excess_percent_p16,
                                 r.u_excess_percent_p84-r.u_excess_percent_p50, 1))
        u_tex.append(" & ".join(vals) + r" \\")
    (output / "sed_u_excess.tex").write_text(compact_table("lcc", "RMS SED U-band fractional excess before and after decomposition.",
        "tab:sed_u_excess", r"AGN & Before (\%) & After (\%)",
        u_tex, r"The excess is $100(S_U/\widehat S_{U,-U}-1)$, where $S=\lambda R_\lambda$ and "
        r"$\widehat S_{U,-U}$ is predicted by a free-index power-law fit excluding U. "
        r"Before and after denote the total-variable and short-lag components. "
        r"Uncertainties give the 16th--84th percentile interval of each component's joint FFA posterior."))

    mica_tex = []
    for source in sources:
        if mica_tex:
            mica_tex.append(r"\hline")
        band_rows = [only(mica, source=source, band=band) for band in BANDS[1:]]
        quantities = [
            (r"$\langle\tau\rangle_{\rm short}$ (days)",
             [interval(r.tau_short, r.tau_short_err_low, r.tau_short_err_high, 3) for r in band_rows]),
            (r"$\langle\tau\rangle_{\rm delayed}$ (days)",
             [interval(r.tau_delayed, r.tau_delayed_err_low, r.tau_delayed_err_high, 2) for r in band_rows]),
            (r"${\rm RMS}_{\rm short}/{\rm RMS}_{\rm delayed}$", [f"{r.rms_ratio:.2f}" for r in band_rows]),
        ]
        for index, (quantity, values) in enumerate(quantities):
            mica_tex.append(" & ".join([tex_name(source) if index == 0 else "", quantity, *values]) + r" \\")
    mica_head = " & ".join(r"\colhead{" + label + "}" for label in ("AGN", "Quantity", *BANDS[1:]))
    (output / "mica_parameters.tex").write_text(table("llccccc", "MICA decomposition parameters.",
        ["tab:mica_summary"], mica_head, mica_tex,
        r"Lags are observer-frame centroids relative to UVW2, with central 68.27\% posterior intervals. "
        r"RMS ratios are measured from the reconstructed component mean light curves within each band's observed interval.",
        placement="!ht"))

    distance_tex = []
    for source in sources:
        vals = [tex_name(source)]
        for band in BANDS:
            r = only(distance, source=source, band=band)
            vals.append(interval(r.D_L_mpc, r.D_L_err_low, r.D_L_err_high, 1))
        distance_tex.append(" & ".join(vals) + r" \\")
    distance_head = (
        " & ".join([r"\colhead{AGN}", *[r"\colhead{$D_L(\mathrm{" + band + r"})$}" for band in BANDS]])
        + r" \\" + "\n" + " & ".join([r"\colhead{}", *[r"\colhead{(Mpc)}" for _ in BANDS]])
    )
    (output / "band_distances.tex").write_text(table("lcccccc", "Band-by-band standard-disk luminosity-distance diagnostics.",
        ["tab:band_distances", "tab:all_distance_h0"], distance_head, distance_tex,
        r"These band estimates use $D_L=(1+z)D_{\rm M}$ and central 68.27\% posterior intervals. "
        r"They provide a band-consistency diagnostic and are not the inputs to the joint $H_0$ inference.",
        placement="!ht"))

    shared_dir = downstream / "joint_hubble_shared_sed_no_f0"
    shared_path = shared_dir / "source_distance_summary.csv"
    h0_path = shared_dir / "h0_summary.csv"
    shared = pd.read_csv(shared_path).set_index("source").loc[sources].reset_index()
    h0 = pd.read_csv(h0_path)
    if len(h0) != 1 or int(h0.iloc[0].n_sources) != len(sources):
        raise ValueError("Joint H0 result does not match the paper sample")
    if not (shared.sed_constraints.eq(5).all() and shared.n_bands.eq(6).all()):
        raise ValueError("Shared SED model does not have five shape constraints in six bands")
    if not shared.mcmc_converged.all() or not bool(h0.iloc[0].mcmc_converged):
        raise ValueError("Shared SED/H0 result has an unconverged sampler")
    shared_tex = []
    for r in shared.itertuples():
        shared_tex.append(" & ".join([tex_name(r.source),
            interval(r.D_q50, r.D_q50-r.D_q16, r.D_q84-r.D_q50, 1),
            f"${r.D_mean:.1f}\\pm{r.D_std:.1f}$", f"{r.sed_delta_chi2_reviewed:.2f}"]) + r" \\")
    shared_head = r"""\colhead{AGN} & \colhead{$D_L$} & \colhead{$\langle D_L\rangle\pm\sigma_{D_L}$} & \colhead{$-2\Delta\ln\mathcal L_{\rm SED}$} \\
\colhead{} & \colhead{(Mpc)} & \colhead{(Mpc)} & \colhead{}"""
    (output / "shared_distances.tex").write_text(table("lccc",
        "Source distances under the shared standard-SED model.",
        ["tab:distance_h0", "tab:shared_distances"], shared_head, shared_tex,
        r"The second column gives posterior medians and central 68.27\% intervals; "
        r"the third gives the means and standard deviations used in the joint $H_0$ likelihood. "
        r"The last column compares the standard SED with six independent RMS amplitudes using the exact FFA likelihood, "
        r"with five spectral-shape constraints."))
    shared["input_file"] = str(shared_path)
    shared.to_csv(output / "shared_distances.csv", index=False)
    h0["input_file"] = str(h0_path)
    h0.to_csv(output / "joint_result.csv", index=False)
    h = h0.iloc[0]
    result_macro = (f"{h.h0_q50:.1f}^{{+{h.h0_q84-h.h0_q50:.1f}}}_{{-{h.h0_q50-h.h0_q16:.1f}}}"
                    + r"\,\mathrm{km\,s^{-1}\,Mpc^{-1}}")
    (output / "joint_result.tex").write_text(
        "% Generated from the selected shared-SED result.\n"
        + r"\renewcommand{\jointHubbleResult}{\ensuremath{" + result_macro + "}}\n")

    before = u[u.stage.eq("before")].set_index("source")
    after = u[u.stage.eq("after")].set_index("source")
    decreased = [s for s in sources if after.loc[s, "u_excess_percent_p50"] < before.loc[s, "u_excess_percent_p50"]]
    facts = dict(n_sources=len(sources), u_excess_decreased_sources=decreased,
        u_excess_increased_sources=[s for s in sources if s not in decreased],
        alpha_min=float(fits.alpha.min()), alpha_max=float(fits.alpha.max()),
        beta_min=float(fits.beta.min()), beta_max=float(fits.beta.max()),
        sed_fixed_chi2_dof_below_one=int((fits.sed_chi2_fixed/fits.sed_dof_fixed < 1).sum()),
        lag_fixed_chi2_dof_below_one=int((fits.lag_chi2_fixed/fits.lag_dof_fixed < 1).sum()))
    manifest = dict(stage=STAGE, sources=sources, omitted_sample_sources=omitted,
        omission_reason="No completed relaxed-Gamma downstream result; no base-branch substitution.",
        sample_table=str(sample_path), aggregate_inputs=[str(p) for p in
            (summary_path, sed_path, lag_path, distance_path, shared_path, h0_path)],
        source_inputs=provenance, definitions=dict(
            sed="lambda times FFA R; free/fixed alpha summaries use all six bands; fixed alpha=-4/3",
            sed_quantiles=[16, 50, 84], sed_chi2="median of per-posterior-draw fitted chi-square statistics",
            lag="relative to UVW2 in observer days; fixed beta=4/3; supplied chi-square and fit summaries",
            lag_and_mica_quantiles=[15.865, 50, 84.135],
            u_excess="100*(observed lambda*R_U / leave-U-out free power-law prediction - 1)",
            u_weight="sigma_log=max(0.5*(p84-p16)/p50,1e-4) from lambda*R marginal posterior; inverse variance",
            u_posterior_scope="Joint within each FFA stage only; independent before/after draws are never paired",
            u_quantiles=[16, 50, 84],
            rms="RMS of native reconstructed component mean curves over each response-band observed interval; no error interval",
            distance="Saved standard-disk D, D_err_low/high multiplied by 1+the saved distance z to form D_L",
            distance_quantiles=[15.865, 50, 84.135], distance_used_in_joint_h0=False,
            shared_distance="Saved luminosity distance D_L; no additional redshift factor; mean/std enter joint H0",
            shared_distance_quantiles=[15.865, 50, 84.135],
            shared_sed_statistic="Reviewed -2 log likelihood difference: exact FFA standard SED versus independent six-band RMS; five shape constraints",
            joint_h0="Selected shared standard-SED model; one distance per source; f0=0; no peculiar-velocity term"),
        facts=facts, generated_files=[str(p) for p in sorted(output.glob("*.tex"))]+[
            str(output/f"{name}.csv") for name in ("short_component_fits", "sed_u_excess", "mica_parameters", "band_distances", "shared_distances", "joint_result")])
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(facts, indent=2))
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", type=Path, default=ROOT)
    parser.add_argument("--downstream", type=Path)
    parser.add_argument("--output-dir", type=Path)
    args = parser.parse_args()
    workspace = args.workspace.resolve()
    render(workspace, (args.downstream or workspace/"output/gamma_relaxed_downstream_20260903").resolve(),
           (args.output_dir or workspace/"DRMH0/tables/relaxed").resolve())


if __name__ == "__main__":
    main()
