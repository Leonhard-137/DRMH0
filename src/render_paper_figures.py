#!/usr/bin/env python3
# 论文图表总装入口：调用既有产物绘图器并生成 TeX include 文本。
# main.py all 不会自动执行这里；本脚本也不会编译论文或重跑采样。
"""Render the agreed FFA, MICA and SED/lag figures and assemble paper includes.

The sample order comes from Section 2's sample_observations.csv. All MICA
products use one explicitly selected result branch. Existing fit products
are read; this command does not run inference or compile the manuscript.
"""
from pathlib import Path
import argparse
import csv
import json
import re


ROOT = Path(__file__).resolve().parents[1]


def tex_name(source):
    base, separator, segment = source.partition("_")
    base = re.sub(r"^(Mrk|NGC)(?=\d)", r"\1~", base)
    base = re.sub(r"^F(?=\d)", "Fairall~", base)
    return base


# 生成含图和图注的 TeX 页面片段，跨页续图与浮动体有不同处理。
def page_block(path, caption, label=None, continuation=None):
    """A full-width, non-floating page keeps a multi-page figure together."""
    if continuation:
        text = (r"\noindent{\footnotesize\textbf{Figure~\ref{" + continuation
                + r"} (continued).} " + caption + r"}\par")
    else:
        text = r"\figcaption{" + caption + r"\label{" + label + "}}"
    return "\n".join([
        r"\begin{center}", r"\begin{minipage}{\textwidth}", r"\centering",
        r"\includegraphics[width=\textwidth,height=0.83\textheight,keepaspectratio]{" + path + "}",
        r"\par\vspace{0.25em}", text,
        r"\end{minipage}", r"\end{center}", "",
    ])


# 核对所有预期 PDF、样本顺序和 stage 来源清单，再生成论文引用片段。
# 入口要求主文示例 Mrk817_a 存在；路径存在并不自动证明上游结果最新。
def assemble(workspace, sources, stage):
    paper = workspace / "DRMH0"
    out = paper / "fig/paper"
    example = "Mrk817_a"
    if example not in sources:
        raise ValueError("The agreed main-text example Mrk817_a is absent from the sample")
    other_sources = [s for s in sources if s != example]
    ffa = {s: f"fig/paper/ffa/{s}_total_ffa_host_diagnostics.pdf" for s in sources}
    mica = {s: f"fig/paper/mica/Fig2_{s}_mica_decomposition.pdf" for s in sources}
    sed = {s: f"fig/paper/sed_lag/Fig3_{s}_sed_lag.pdf" for s in sources}
    sed_pages = [f"fig/paper/sed_lag/Fig3_sed_lag_page{i+1}.pdf"
                 for i in range((len(sources) + 9) // 10)]
    ffa_pages = [f"fig/paper/ffa/FigA_ffa_{i+1:02d}.pdf"
                 for i in range((len(other_sources) + 5) // 6)]
    expected = [*ffa.values(), *mica.values(), *sed.values(), *sed_pages, *ffa_pages]
    missing = [p for p in expected if not (paper / p).is_file()]
    if missing:
        raise FileNotFoundError("Missing paper figure products:\n" + "\n".join(missing))
    for kind in ("ffa", "mica", "sed_lag"):
        manifest_path = out / kind / "manifest.json"
        if not manifest_path.is_file():
            raise FileNotFoundError(manifest_path)
        manifest = json.loads(manifest_path.read_text())
        if kind == "ffa" and manifest.get("source_order") != sources:
            raise ValueError("FFA figure sample does not match Section 2")
        if kind != "ffa" and manifest.get("stage") != stage:
            raise ValueError(f"{kind} figures do not belong to the requested branch {stage}")
        if kind != "ffa" and manifest.get("sources") != sources:
            raise ValueError(f"{kind} figure sample does not match Section 2")

    ffa_caption = (
        r"Flux--flux analysis of Mrk~817 over the selected monitoring interval. "
        r"Left: the six-band fluxes as functions of the common variability $X(t)$, "
        r"with the fitted linear relations and their extrapolations. "
        r"Right: the bright- and faint-state AGN spectra, RMS variability spectrum, "
        r"bright-minus-faint spectrum, and estimated host-galaxy contribution. "
        r"The corresponding diagnostics for the remaining sources are shown in "
        r"Appendix~\ref{app:ffa_diagnostics}."
    )
    mica_caption = (
        r"MICA decomposition of Mrk~817. The top-left panel shows the UVW2 driver; "
        r"the remaining left panels show the observed response-band light curves "
        r"(black points), total reconstruction (black), short-lag component "
        r"(dark blue), and long-lag component (orange). Shaded regions show the "
        r"native reconstruction uncertainties. The right panels show the total "
        r"transfer functions: median curves with 15.85th--84.15th percentile bands, "
        r"on logarithmic ordinate axes and over the saved lag ranges. "
        r"Times and lags are in the observer frame. Other sources are shown in "
        r"Appendix~\ref{app:mica_decomp}."
    )
    for name, path, caption, label in (
        ("ffa_example", ffa[example], ffa_caption, "fig:ffa_host_diagnostics"),
        ("mica_example", mica[example], mica_caption, "fig:mica_decomposition"),
    ):
        text = "\n".join([
            "% Generated by src/render_paper_figures.py.",
            r"\begin{figure*}[p]" if name == "mica_example" else r"\begin{figure*}[t]",
            r"\centering",
            r"\includegraphics[width=\textwidth,height=0.83\textheight,keepaspectratio]{" + path + "}",
            r"\caption{" + caption + r"\label{" + label + "}}",
            r"\end{figure*}", "",
        ])
        (out / f"{name}.tex").write_text(text)

    sed_caption = (
        r"Variable SEDs (left panel of each pair) and short-component lag spectra (right panel) for the "
        r"full sample. Gray open squares show the SED before decomposition; "
        r"dark-blue circles show the short-lag component. Each SED is displayed "
        r"as $\lambda R_\lambda/C_{\rm W2}$, where $C_{\rm W2}$ is its fixed "
        r"UVW2 median. Error bars retain the original FFA $R_\lambda$ "
        r"16th--84th percentile intervals after this fixed scaling, including "
        r"the UVW2 uncertainty. The dashed SED curve is the SSD shape "
        r"$(\lambda/\lambda_{\rm W2})^{-4/3}$ through the common anchor, "
        r"not a fitted normalization. The lag panels show the short-component "
        r"Gamma centroids relative to UVW2 and the saved $\beta=4/3$ fits "
        r"with their posterior intervals. Wavelengths and lags are in the observer frame."
    )
    chunks = [sources[i:i+10] for i in range(0, len(sources), 10)]
    blocks = ["% Generated by src/render_paper_figures.py.", r"\clearpage", r"\onecolumngrid"]
    for i, (path, chunk) in enumerate(zip(sed_pages, chunks)):
        if i:
            blocks.append(r"\clearpage")
        caption = ("Sources from left to right, then top to bottom: " + ", ".join(map(tex_name, chunk)) + ".")
        blocks.append(page_block(path, sed_caption + " " + caption if i == 0 else caption,
                                 label="fig:short_component_diagnostics",
                                 continuation="fig:short_component_diagnostics" if i else None))
    blocks.extend([r"\clearpage", r"\twocolumngrid", ""])
    (out / "sed_lag_figures.tex").write_text("\n".join(blocks))

    blocks = ["% Generated by src/render_paper_figures.py.", r"\clearpage", r"\onecolumngrid",
              r"\section{Flux--Flux Diagnostics}", r"\label{app:ffa_diagnostics}",
              r"\setcounter{figure}{0}"]
    for i, path in enumerate(ffa_pages):
        if i:
            blocks.append(r"\clearpage")
        names = ", ".join(map(tex_name, other_sources[6*i:6*i+6]))
        caption = (f"Flux--flux diagnostics for {names}, from left to right, then top to bottom. "
                   + r"The layout and symbols are the same as in Figure~\ref{fig:ffa_host_diagnostics}.")
        blocks.append(page_block(path, caption, label="fig:all_ffa_diagnostics",
                                 continuation="fig:all_ffa_diagnostics" if i else None))
    blocks.extend([r"\clearpage", r"\section{MICA Decomposition Diagnostics}",
                   r"\label{app:mica_decomp}", r"\setcounter{figure}{0}"])
    for i, source in enumerate(other_sources):
        if i:
            blocks.append(r"\clearpage")
        caption = (f"MICA decomposition and total transfer functions for {tex_name(source)}. "
                   + r"The layout and symbols are the same as in Figure~\ref{fig:mica_decomposition}.")
        blocks.append(page_block(mica[source], caption, label="fig:all_mica_decompositions",
                                 continuation="fig:all_mica_decompositions" if i else None))
    blocks.extend([r"\clearpage", r"\twocolumngrid", ""])
    (out / "appendix_figures.tex").write_text("\n".join(blocks))
    manifest = dict(sources=sources, stage=stage, example_source=example,
                    single_source_figure_count=len(sources)*3,
                    main_text=dict(ffa=ffa[example], mica=mica[example], sed_lag=sed_pages),
                    appendix=dict(ffa=ffa_pages, mica=[mica[s] for s in other_sources]),
                    all_single_source_figures=dict(ffa=ffa, mica=mica, sed_lag=sed),
                    includes=[f"fig/paper/{s}.tex" for s in
                              ("ffa_example", "mica_example", "sed_lag_figures", "appendix_figures")])
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


# 先按样本表/方案选择绘图任务，再装配论文使用的文件；所有输出均有写盘副作用。
def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", type=Path, default=ROOT)
    parser.add_argument("--stage", default="mica_gamma2_physw_relaxed")
    parser.add_argument("--assemble-only", action="store_true", help="Reuse rendered figures and update TeX includes")
    parser.add_argument("--reuse-ffa", action="store_true", help="Reuse saved single-source FFA figures and rebuild their appendix pages")
    args = parser.parse_args(argv)
    workspace = args.workspace.resolve()
    sample_table = workspace / "DRMH0/tables/sample_observations.csv"
    with sample_table.open() as handle:
        sources = [row["source"] for row in csv.DictReader(handle)]
    if not args.assemble_only:
        from plot_ffa_paper import build_ffa_paper
        from plot_mica_decomposition_paper import render_sample as render_mica
        from plot_sed_lag_paper import render_sample as render_sed_lag
        out = workspace / "DRMH0/fig/paper"
        build_ffa_paper(sample_table, out / "ffa", reuse_existing=args.reuse_ffa)
        render_mica(workspace, sources, out / "mica", args.stage)
        render_sed_lag(workspace, sources, out / "sed_lag", args.stage)
    manifest = assemble(workspace, sources, args.stage)
    print(f"Prepared {manifest['single_source_figure_count']} single-source figures and paper includes.")
    print(workspace / "DRMH0/fig/paper/manifest.json")


if __name__ == "__main__":
    main()
